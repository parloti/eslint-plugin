import { describe, expect, it } from "vitest";

import {
  runFix,
  runVerifyAndFix,
} from "./__tests__/prefer-interface-types-autofix-test-helpers";

describe("prefer interface types outermost matches", () => {
  it("fixes method input, function input, return, and nested callback input together", () => {
    // Arrange
    const code = [
      "interface DashboardEventPublisher {",
      "  publish(input: { eventType: string; payload: unknown }): void;",
      "}",
      "function createManagedPortfolioSyncEventBridge(input: {",
      "  dashboardEventPublisher: DashboardEventPublisher;",
      "}): {",
      "  onPortfolioSyncFailure: (failure: { accountId: string; summary: string }) => void;",
      "} {",
      "  return { onPortfolioSyncFailure: (failure) => input.dashboardEventPublisher.publish({ eventType: failure.accountId, payload: failure.summary }) };",
      "}",
    ].join("\n");

    // Act
    const actual = runVerifyAndFix(code);

    // Assert
    expect(actual.messages).toHaveLength(4);
    expect(actual.messages[0]?.fix).toBeDefined();
    expect(actual.fixResult.fixed).toBe(true);
    expect(actual.fixResult.messages).toStrictEqual([]);
    expect(actual.fixResult.output).toBe(
      [
        "interface DashboardEventPublisher {",
        "  publish(input: Input): void;",
        "}",
        "function createManagedPortfolioSyncEventBridge(input: Input1): CreateManagedPortfolioSyncEventBridge {",
        "  return { onPortfolioSyncFailure: (failure) => input.dashboardEventPublisher.publish({ eventType: failure.accountId, payload: failure.summary }) };",
        "}",
        "",
        "// TODO: Review this autogenerated type name",
        "interface Input { eventType: string; payload: unknown }",
        "",
        "// TODO: Review this autogenerated type name",
        "interface Input1 {",
        "  dashboardEventPublisher: DashboardEventPublisher;",
        "}",
        "",
        "// TODO: Review this autogenerated type name",
        "interface CreateManagedPortfolioSyncEventBridge {",
        "  onPortfolioSyncFailure: (failure: Failure) => void;",
        "}",
        "",
        "// TODO: Review this autogenerated type name",
        "interface Failure { accountId: string; summary: string }",
        "",
      ].join("\n"),
    );
  });

  it("fixes multiple levels of nested signatures and sibling callbacks", () => {
    // Arrange
    const code =
      "declare function create(): { first: (input: { next: (value: { id: string }) => void }) => void; second: (input: { active: boolean }) => void };";

    // Act
    const actual = runFix(code);

    // Assert
    expect(actual.fixed).toBe(true);
    expect(actual.messages).toStrictEqual([]);
    expect(actual.output).toContain("declare function create(): Create;");
    expect(actual.output).toContain(
      "interface Create { first: (input: Input) => void; second: (input: Input1) => void }",
    );
    expect(actual.output).toContain(
      "interface Input { next: (value: Value) => void }",
    );
    expect(actual.output).toContain("interface Input1 { active: boolean }");
    expect(actual.output).toContain("interface Value { id: string }");
  });

  it("does not change nested signatures after autofixing", () => {
    // Arrange
    const code =
      "declare function create(): { handle: (input: { id: string }) => void };";

    // Act
    const actual = runFix(runFix(code).output);

    // Assert
    expect(actual.fixed).toBe(false);
    expect(actual.output).toContain("declare function create(): Create;");
    expect(actual.output).toContain(
      "interface Create { handle: (input: Input) => void }",
    );
    expect(actual.output).toContain("interface Input { id: string }");
    expect(actual.messages).toStrictEqual([]);
  });

  it("does not relocate nested signatures that reference an enclosing generic", () => {
    // Arrange
    const code =
      "declare function create<T>(): { handle: (input: { value: T }) => void };";

    // Act
    const actual = runVerifyAndFix(code);

    // Assert
    expect(actual.messages).toHaveLength(2);
    expect(actual.fixResult.fixed).toBe(false);
    expect(actual.fixResult.output).toBe(code);
  });
});
